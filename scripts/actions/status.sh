#!/usr/bin/env bash
# action: status - sub-repo state, build artifacts, images and devices
# usage: bash scripts/actions/status.sh [target ...]
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/common.sh
source "$SCRIPT_DIR/../lib/common.sh"

TARGETS="${1:-${TARGETS:-$ALL_TARGETS}}"

du_h() { du -sh "$1" 2>/dev/null | awk '{print $1}' || true; }
# git fails outside a git repo; with pipefail the whole pipeline is non-zero, so
# assign with an explicit fallback to avoid printing the count twice
sub_count() { local n; n=$(git -C "$1" submodule status 2>/dev/null | wc -l | tr -d ' ') || n=0; printf '%s' "${n:-0}"; }
sub_missing() { local n; n=$(git -C "$1" submodule status 2>/dev/null | grep -c '^-') || n=0; printf '%s' "${n:-0}"; }

row() { printf '  %-16s %s\n' "$1" "$2"; }

printf '\n\033[1mRVOCs environment and artifacts\033[0m  arch=%s  siblings=%s\n' "$ARCH" "$SIBLINGS_DIR"
printf 'workdir: %s\n' "$WORK_DIR"

for t in $TARGETS; do
  echo
  printf '\033[1;36m== %s ==\033[0m %s\n' "$t" "$(repo_label "$t" 2>/dev/null || echo '?')"
  if ! dir=$(repo_dir "$t" 2>/dev/null); then
    row "repo" "$(printf '\033[1;33mnot found\033[0m')  candidates: $SIBLINGS_DIR/{$(repo_dirs_for "$t" | tr ' ' '|')}"
    continue
  fi
  row "repo" "$dir"
  row "branch/commit" "$(repo_branch "$t") @ $(repo_head "$t")  dirty=$(repo_dirty_count "$t")"
  if [ "$t" != rvocs ]; then
    _subs=$(sub_count "$dir"); _miss=$(sub_missing "$dir")
    row "submodules" "${_subs} total (${_miss} uninitialized)"
  fi
  case "$t" in
    rvocs)
      row "docs" "$(ls -1 "$REPO_ROOT/docs" 2>/dev/null | wc -l | tr -d ' ') files under docs/"
      ;;
    tt-stack)
      row "workdir" "$([ -d "$dir/work" ] && echo "$(du_h "$dir/work")" || echo 'not created (use --stage prep)')"
      row "image" "$(image_tag_for tt-stack "$ARCH")"
      row "local image" "$(image_exists "$(image_tag_for tt-stack "$ARCH")" && echo 'present' || echo 'not pulled/built')"
      row "devices" "$(ls -d /dev/tenstorrent* 2>/dev/null | tr '\n' ' ' || echo 'no /dev/tenstorrent')"
      ;;
    therock)
      row "sources/build" "$([ -d "$dir/upstream/therock" ] && echo "upstream/therock $(du_h "$dir/upstream/therock")" || echo 'submodule not initialized')"
      row "rocm artifacts" "$([ -d "$dir/upstream/therock/build/dist/rocm" ] && echo "dist/rocm $(du_h "$dir/upstream/therock/build/dist/rocm")" || echo 'not built')"
      row "venv/wheels" "$([ -d "$dir/work/venv-stack" ] && echo "venv-stack $(du_h "$dir/work/venv-stack")" || echo 'not assembled')"
      row "image" "$(image_tag_for therock "$ARCH")"
      row "local image" "$(image_exists "$(image_tag_for therock "$ARCH")" && echo 'present' || echo 'not built')"
      row "devices" "$(ls -d /dev/kfd /dev/dri/renderD* 2>/dev/null | tr '\n' ' ' || echo 'no /dev/kfd /dev/dri')"
      ;;
    tt-host)
      row "sources" "$([ -d "$dir/work/src" ] && echo "work/src $(du_h "$dir/work/src")" || echo 'not fetched')"
      row "artifacts" "$(ls -1 "$dir/$(repo_part "$t")/dist" 2>/dev/null | tr '\n' ' ' || echo 'none (generated by --build)')"
      ;;
  esac
done

echo
printf '\033[1;36m== host ==\033[0m\n'
row "arch/distro" "$(uname -m)  $( (. /etc/os-release 2>/dev/null && echo "$PRETTY_NAME") || echo 'unknown')"
row "docker" "$(have_cmd docker && (docker version --format '{{.Server.Version}}' 2>/dev/null || echo 'CLI present, daemon unavailable') || echo 'not installed')"
row "disk free" "$(df -Pk "$WORK_DIR" 2>/dev/null | awk 'NR==2 {printf "%d GB", int($4/1048576)}' || echo '?')"
row "1G hugepages" "$(awk '/^HugePages_Total/ {print $2}' /proc/meminfo 2>/dev/null || echo '?') pages"
